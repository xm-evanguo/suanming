const word = (table: Record<string, string>) => (s: string) => (isEn() ? (table[s] ?? s) : s);
/** "天同" → "Tian Tong". */
export const starName = word(STAR_EN);
/** "官禄" → "Career"; English adds "palace" where the sentence needs it. */
export const palaceName = word(PALACE_EN);
export const brightName = word(BRIGHT_EN);
/** "禄" → "Lu". */
export const mutagenName = word(MUTAGEN_EN);
export const mutagenGloss = (m: string) => MUTAGEN_GLOSS[m] ?? m;
export const bureauName = word(CLASS_EN);
/** "天同化禄" style: "Tian Tong Hua Lu". */
export const huaName = (star: string, m: string) => (isEn() ? `${starName(star)} Hua ${mutagenName(m)}` : `${star}化${m}`);
