import type { Scores, WuXing } from "./types";

export interface Hexagram {
  /** King Wen sequence number, 1-64. */
  num: number;
  /** Short name, e.g. "屯". */
  name: string;
  /** Full name, e.g. "水雷屯". */
  fullName: string;
  /** Upper trigram name (one of 乾 兑 离 震 巽 坎 艮 坤). */
  upper: string;
  /** Lower trigram name (one of 乾 兑 离 震 巽 坎 艮 坤). */
  lower: string;
  /** Original judgment text (卦辞). */
  judgment: string;
  /** The Great Image line (大象传). */
  image: string;
  /** Modern interpretation for a personal reading. */
  meaning: string;
  keywords: string[];
  scores: Scores;
}

